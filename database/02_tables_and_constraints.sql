-- 1. ROLES
CREATE TABLE ROLES (
    ID              NUMBER(19) DEFAULT SEQ_ROLES.NEXTVAL NOT NULL,
    ROLE_CODE       VARCHAR2(50) NOT NULL,
    ROLE_NAME       VARCHAR2(100) NOT NULL,
    DESCRIPTION     VARCHAR2(255),
    STATUS          VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CREATED_BY      VARCHAR2(50) DEFAULT 'SYSTEM',
    UPDATED_BY      VARCHAR2(50) DEFAULT 'SYSTEM',
    CONSTRAINT PK_ROLES PRIMARY KEY (ID),
    CONSTRAINT UK_ROLES_CODE UNIQUE (ROLE_CODE),
    CONSTRAINT CHK_ROLES_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE'))
);

